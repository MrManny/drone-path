import { execFile } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';

import { VERSION } from './version.js';

const execFileAsync = promisify(execFile);

/** What the git probe found at build time; null when git was unavailable. */
export interface GitProbe {
  /** Full commit of HEAD, or null outside a repository. */
  headCommit: string | null;
  /** Tags pointing at HEAD. */
  tagsAtHead: readonly string[];
}

/** The facts the generated module carries, matching ui/lib/buildversion.ts. */
export interface BuildGit {
  tagged: boolean;
  commit: string | null;
}

export interface BuildinfoPaths {
  moduleFile: string;
}

export function defaultBuildinfoPaths(root: string): BuildinfoPaths {
  return {
    moduleFile: path.join(root, 'ui', 'lib', 'buildinfo', 'generated', 'buildinfo.ts'),
  };
}

export function resolveBuildGit(version: string, probe: GitProbe | null): BuildGit | null {
  const commit = probe?.headCommit?.trim() ?? '';
  if (probe === null || commit === '') return null;
  // Only the matching v<version> tag marks a formal release; any other state
  // keeps the commit hash visible.
  return { tagged: probe.tagsAtHead.includes(`v${version}`), commit: commit.slice(0, 8) };
}

export function buildinfoModuleSource(version: string, git: BuildGit | null): string {
  return (
    '// Generated by src/buildinfo.ts at build time. Do not edit.\n' +
    "import type { BuildGit } from '../../buildversion.js';\n" +
    '\n' +
    `export const BUILD_VERSION = ${JSON.stringify(version)};\n` +
    `export const BUILD_GIT: BuildGit | null = ${JSON.stringify(git)};\n`
  );
}

export function buildBuildinfo(
  paths: BuildinfoPaths,
  version: string,
  probe: GitProbe | null,
): BuildGit | null {
  const git = resolveBuildGit(version, probe);
  fs.mkdirSync(path.dirname(paths.moduleFile), { recursive: true });
  fs.writeFileSync(paths.moduleFile, buildinfoModuleSource(version, git));
  return git;
}

async function tryGit(args: readonly string[]): Promise<string | null> {
  try {
    const { stdout } = await execFileAsync('git', [...args]);
    return stdout;
  } catch {
    return null;
  }
}

export async function probeGit(): Promise<GitProbe | null> {
  const head = await tryGit(['rev-parse', 'HEAD']);
  if (head === null) return null;
  // A missing tag list only means HEAD is untagged, not that git is gone.
  const tags = await tryGit(['tag', '--points-at', 'HEAD']);
  return {
    headCommit: head.trim(),
    tagsAtHead: (tags ?? '')
      .split('\n')
      .map((tag) => tag.trim())
      .filter((tag) => tag !== ''),
  };
}

async function main(): Promise<void> {
  try {
    const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
    const git = buildBuildinfo(defaultBuildinfoPaths(root), VERSION, await probeGit());
    const detail = git === null ? 'no git' : git.tagged ? 'tagged' : `commit ${git.commit}`;
    process.stderr.write(`[drone-path] buildinfo: ${VERSION} (${detail})\n`);
  } catch (e) {
    process.stderr.write(`[drone-path] ERROR: ${(e as Error).message}\n`);
    process.exitCode = 1;
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  void main();
}
