import {
  CONFIG_FILE_OPTION,
  CONFIG_OPTIONS,
  TELEMETRY_JSON_ALIAS,
  cliDefaultOf,
} from 'drone-path-engine/config';
import type { ConfigOption, RenderConfig } from 'drone-path-engine/config';
import { escapeAngleBrackets } from './markdown.js';

function defaultCell(key: keyof RenderConfig): string {
  const value = cliDefaultOf(key);
  if (typeof value === 'boolean') return value ? 'on' : 'off';
  return value === '' ? '—' : `\`${value}\``;
}

function describe(row: ConfigOption): string {
  const help = escapeAngleBrackets(row.cli.help);
  return row.cli.choices ? `${help} (choices: ${row.cli.choices.join(', ')})` : help;
}

export function generateCliReference(): string {
  const rows = CONFIG_OPTIONS.map(
    (row) =>
      `| \`${row.key}\` | \`${row.cli.flags}\` | ${defaultCell(row.key)} | ${describe(row)} |`,
  );
  rows.push(`| — | \`${CONFIG_FILE_OPTION.flags}\` | — | ${CONFIG_FILE_OPTION.help} |`);
  rows.push(
    `| \`${TELEMETRY_JSON_ALIAS.inputKey}\` | \`${TELEMETRY_JSON_ALIAS.flags}\` | — | ` +
      `deprecated alias of --track-out &lt;file&gt;.json: same output, warns on use, ` +
      `removed in a future version |`,
  );
  return [
    '<!-- Generated by "npm run docs:reference". Do not edit by hand. -->',
    '',
    '# CLI and config reference',
    '',
    '## Render options',
    '',
    'In a [config file](config-file.md), omitted render options use the defaults',
    'below. Run `npx drone-path --help` for terminal help.',
    '',
    '| Config key | CLI flag | Default | Description |',
    '|---|---|---|---|',
    ...rows,
    '',
    '## `extract-frame`',
    '',
    'Extract JPEG keyframes and telemetry snapshots from a recording.',
    '',
    '```sh',
    'drone-path extract-frame <video> --at <specs> [options]',
    '```',
    '',
    'Use `--at` with comma-separated timestamps in seconds or zero-based frame',
    'selectors such as `f90`. Add `--sharpness` to score each frame and `--json`',
    'to write the results as a JSON array to stdout.',
    '',
    'See [Extract keyframes](cli.md#extract-keyframes) for the full option list,',
    'output fields, and examples.',
    '',
  ].join('\n');
}
