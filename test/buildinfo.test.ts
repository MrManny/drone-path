import fs from 'node:fs';
import path from 'node:path';

import { afterEach, describe, expect, it } from 'vitest';

import type { GitProbe } from '../src/buildinfo.js';
import {
  buildBuildinfo,
  buildinfoModuleSource,
  defaultBuildinfoPaths,
  resolveBuildGit,
} from '../src/buildinfo.js';
import { cleanupTmpDirs, tmpDir } from './fixtures.js';

afterEach(cleanupTmpDirs);

const HEAD = 'cb40df329f1a83b6f01c24a8314f58b9a17d4e55';

describe('resolveBuildGit', () => {
  it('marks HEAD tagged when it carries the v<version> tag', () => {
    const probe: GitProbe = { headCommit: HEAD, tagsAtHead: ['v0.8.1'] };
    expect(resolveBuildGit('0.8.1', probe)).toEqual({ tagged: true, commit: 'cb40df32' });
  });

  it('keeps the commit for an untagged HEAD', () => {
    const probe: GitProbe = { headCommit: HEAD, tagsAtHead: [] };
    expect(resolveBuildGit('0.8.1', probe)).toEqual({ tagged: false, commit: 'cb40df32' });
  });

  it('treats a mismatched version tag as untagged', () => {
    const probe: GitProbe = { headCommit: HEAD, tagsAtHead: ['v0.8.2'] };
    expect(resolveBuildGit('0.8.1', probe)).toEqual({ tagged: false, commit: 'cb40df32' });
  });

  it.for([
    { name: 'git was unavailable', probe: null },
    { name: 'HEAD was unknown', probe: { headCommit: null, tagsAtHead: [] } },
    { name: 'HEAD was empty', probe: { headCommit: '  ', tagsAtHead: [] } },
  ])('yields no facts when $name', ({ probe }) => {
    expect(resolveBuildGit('0.8.1', probe)).toBeNull();
  });
});

describe('buildinfoModuleSource', () => {
  it('emits the version and facts deterministically', () => {
    expect(buildinfoModuleSource('0.8.1', { tagged: false, commit: 'cb40df32' })).toBe(
      '// Generated by src/buildinfo.ts at build time. Do not edit.\n' +
        "import type { BuildGit } from '../../buildversion.js';\n" +
        '\n' +
        'export const BUILD_VERSION = "0.8.1";\n' +
        'export const BUILD_GIT: BuildGit | null = {"tagged":false,"commit":"cb40df32"};\n',
    );
  });

  it('emits null facts for a build without git', () => {
    expect(buildinfoModuleSource('0.8.1', null)).toContain(
      'export const BUILD_GIT: BuildGit | null = null;',
    );
  });
});

describe('buildBuildinfo', () => {
  it('writes the generated module with the resolved facts', () => {
    const paths = defaultBuildinfoPaths(tmpDir());
    const git = buildBuildinfo(paths, '0.8.1', { headCommit: HEAD, tagsAtHead: ['v0.8.1'] });
    expect(git).toEqual({ tagged: true, commit: 'cb40df32' });
    expect(fs.readFileSync(paths.moduleFile, 'utf8')).toBe(
      buildinfoModuleSource('0.8.1', git),
    );
    expect(path.basename(paths.moduleFile)).toBe('buildinfo.ts');
  });

  it('writes null facts when git was unavailable', () => {
    const paths = defaultBuildinfoPaths(tmpDir());
    expect(buildBuildinfo(paths, '0.8.1', null)).toBeNull();
    expect(fs.readFileSync(paths.moduleFile, 'utf8')).toContain(
      'export const BUILD_GIT: BuildGit | null = null;',
    );
  });
});
