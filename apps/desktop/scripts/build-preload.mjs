import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

import {
  IPC_EVENT_CHANNELS,
  IPC_INVOKE_CHANNELS,
  IPC_VOID_EVENT_KEYS,
} from '../dist/shared/ipc.js';

const PRELOAD_URL = new URL('../app/preload.cjs', import.meta.url);

export function buildPreloadSource({
  invokeChannels = IPC_INVOKE_CHANNELS,
  eventChannels = IPC_EVENT_CHANNELS,
  voidEventKeys = IPC_VOID_EVENT_KEYS,
} = {}) {
  const invokeLines = Object.entries(invokeChannels).map(
    ([method, channel]) => `  ${method}: (...args) => ipcRenderer.invoke('${channel}', ...args),`,
  );
  const eventLines = Object.entries(eventChannels).map(([method, channel]) =>
    voidEventKeys.has(method)
      ? `  ${method}: (cb) => subscribe('${channel}', () => cb()),`
      : `  ${method}: (cb) => subscribe('${channel}', cb),`,
  );
  return [
    '// Generated by scripts/build-preload.mjs from shared/ipc.ts.',
    '// Preload bridge for the UI: the only surface the renderer sees. CommonJS',
    '// (.cjs) because sandboxed preload scripts cannot use ESM or local require().',
    "const { contextBridge, ipcRenderer } = require('electron');",
    '',
    'function subscribe(channel, adapt) {',
    '  const handler = (_event, payload) => adapt(payload);',
    '  ipcRenderer.on(channel, handler);',
    '  return () => ipcRenderer.removeListener(channel, handler);',
    '}',
    '',
    "contextBridge.exposeInMainWorld('dronepath', {",
    ...invokeLines,
    ...eventLines,
    '});',
    '',
  ].join('\n');
}

function writeIfChanged(targetUrl, content) {
  let existing = '';
  try {
    existing = readFileSync(targetUrl, 'utf8');
  } catch {
    // Missing file will be created below.
  }
  if (existing !== content) writeFileSync(targetUrl, content);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeIfChanged(PRELOAD_URL, buildPreloadSource());
}
