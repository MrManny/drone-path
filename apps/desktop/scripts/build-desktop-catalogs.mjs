import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';

const catalogDir = new URL('../shared/desktop-i18n/catalogs/', import.meta.url);
const outputDir = new URL('../shared/desktop-i18n/generated/', import.meta.url);
const localesDir = new URL('locales/', outputDir);

async function buildCatalogs() {
  const files = (await readdir(catalogDir)).filter((name) => name.endsWith('.json')).sort();
  const entries = await Promise.all(files.map(async (name) => {
    const locale = name.slice(0, -5);
    if (Intl.getCanonicalLocales(locale)[0] !== locale) {
      throw new Error(`catalog file name must use a canonical locale: ${name}`);
    }
    return [locale, JSON.parse(await readFile(new URL(name, catalogDir), 'utf8'))];
  }));
  const catalogs = Object.fromEntries(entries);
  if (!catalogs.en) throw new Error('english desktop catalog is missing');

  const localeIds = entries.map(([locale]) => locale);
  const nonEnglish = localeIds.filter((locale) => locale !== 'en');

  await rm(localesDir, { recursive: true, force: true });
  await mkdir(localesDir, { recursive: true });

  await writeFile(
    new URL('en.ts', outputDir),
    `// Generated by scripts/build-desktop-catalogs.mjs.\n` +
      `export const LOCALES = ${JSON.stringify(localeIds)} as const;\n` +
      `export const englishCatalog = ${JSON.stringify(catalogs.en, null, 2)} as const;\n`,
  );

  await Promise.all(nonEnglish.map((locale) =>
    writeFile(
      new URL(`${locale}.ts`, localesDir),
      `// Generated by scripts/build-desktop-catalogs.mjs.\n` +
        `export const catalog = ${JSON.stringify(catalogs[locale], null, 2)} as const;\n`,
    ),
  ));

  const loaderLines = nonEnglish.map(
    (locale) => `  ${JSON.stringify(locale)}: () => import('./locales/${locale}.js'),`,
  );
  await writeFile(
    new URL('loaders.ts', outputDir),
    `// Generated by scripts/build-desktop-catalogs.mjs.\n` +
      `import type { Catalog, Locale } from '../core.js';\n\n` +
      `export const localeLoaders: Readonly<Record<Exclude<Locale, 'en'>, () => Promise<{ catalog: Catalog }>>> = {\n` +
      `${loaderLines.join('\n')}\n` +
      `};\n`,
  );

  const importLines = nonEnglish.map(
    (locale, index) => `import { catalog as locale${index} } from './locales/${locale}.js';`,
  );
  const mapLines = localeIds.map((locale) => {
    if (locale === 'en') return `  en: englishCatalog,`;
    const index = nonEnglish.indexOf(locale);
    return `  ${JSON.stringify(locale)}: locale${index},`;
  });
  await writeFile(
    new URL('catalogs.ts', outputDir),
    `// Generated by scripts/build-desktop-catalogs.mjs.\n` +
      `import { englishCatalog } from './en.js';\n` +
      `${importLines.join('\n')}\n\n` +
      `export const catalogs = {\n` +
      `${mapLines.join('\n')}\n` +
      `} as const;\n`,
  );
}

buildCatalogs().catch((error) => {
  process.stderr.write(`[drone-path] ERROR: ${error.message}\n`);
  process.exitCode = 1;
});
